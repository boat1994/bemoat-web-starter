function route({
  route_key,
  observed_state,
  evidence_case,
  required_evidence_condition,
  forbidden_evidence_condition,
  permitted_operation,
  canonical_command,
  required_review_type,
  expected_post_state_or_gate,
  prohibited_commands = [],
  decision,
  stop_condition = null,
}) {
  return {
    route_key,
    observed_state,
    evidence_case,
    required_evidence_condition,
    forbidden_evidence_condition,
    permitted_operation,
    canonical_command,
    required_review_type,
    expected_post_state_or_gate,
    prohibited_commands,
    decision,
    stop_condition,
  }
}

